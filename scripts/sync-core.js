// Builds desktop/core.js and desktop/mobile-base.css from the MOBILE app, so both versions share the same logic.
// Usage: npm run sync            (looks for ../lekisa-pilot, or $LEKISA_MOBILE)
//        node scripts/sync-core.js path/to/lekisa-pilot
// The mobile files are only read, never modified.
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const src = path.resolve(process.argv.slice(2).find(a => !a.startsWith("--")) || process.env.LEKISA_MOBILE || path.join(root, "..", "lekisa-pilot"));
const out = path.join(root, "desktop");
const rd = f => fs.readFileSync(path.join(src, f), "utf8");
const optional = process.argv.includes("--optional");
if (optional && !fs.existsSync(path.join(src, "app.js")) && fs.existsSync(path.join(out, "core.js"))) { console.log("Mobile app not found; using the committed desktop/core.js."); process.exit(0); }
if (!fs.existsSync(path.join(src, "app.js"))) { console.error("Mobile app not found at " + src + "\nPass its folder: node scripts/sync-core.js ../lekisa-pilot"); process.exit(1); }

let js = rd("app.js");
const patch = (anchor, replacement, optional) => {
  if (!js.includes(anchor)) {
    if (optional) return console.warn("Skipped optional patch: " + anchor.slice(0, 40));
    throw new Error("Patch anchor not found in app.js: " + anchor.slice(0, 60) + "\nThe mobile app changed. Update scripts/sync-core.js.");
  }
  js = js.replace(anchor, () => replacement);
};

// 1) render() chooses the desktop shell once the user is logged in and unlocked; otherwise the mobile login/lock screens are reused.
patch("function render(){",
  'function render(){const a=$("#app");if(window.LK_DESK&&!locked&&S&&P&&!CONFIG.URL.includes("YOUR-")){a.className="shell";return window.LK_DESK.render()}' +
  'document.querySelectorAll(".ov").forEach(x=>x.remove());a.className="authview";return renderMobile()}\nfunction renderMobile(){');
// 2) expose the internals the desktop UI needs.
patch("D.mm=D.mm||[];applyTheme();",
  'window.LK={$,ls,h,ic,K,F,T,fmt,short,day,mask,par,rw,fld,inp,form,online,pendN,sumT,d0,go,sv,auditTx,sync,lockApp,applyTheme,render,SCREENS,DEF,CONFIG,attn,toCsv,' +
  'get S(){return S},get P(){return P},get D(){return D},get CFG(){return CFG},get locked(){return locked},get lastErr(){return lastErr},' +
  'get view(){return view},set view(v){view=v},get msg(){return msg},set msg(v){msg=v},get rcpt(){return rcpt},set rcpt(v){rcpt=v}};' +
  "const askText=(m,d)=>window.LK_ASK?window.LK_ASK(m,d):Promise.resolve(prompt(m,d));D.mm=D.mm||[];applyTheme();");
// 2b) Electron has no window.prompt(). The Lekisa AI "Edit amount" button uses it, so route it through an async dialog (desk.js provides LK_ASK).
patch('onclick:()=>{const v=prompt("Amount in kwacha"', 'onclick:async()=>{const v=await askText("Amount in kwacha"', true);
// 3) service workers do not run from file://
patch('if("serviceWorker" in navigator)navigator.serviceWorker.register("sw.js").catch(()=>{});', "", true);

fs.writeFileSync(path.join(out, "core.js"), "/* GENERATED by scripts/sync-core.js from the mobile app.js. Do not edit; edit the mobile app and run npm run sync. */\n" + js);
// The lock / "Welcome back" screen is taken from the mobile index.html so desktop always matches it.
const mobileHtml = rd("index.html");
const lock = mobileHtml.match(/<div id="lockscreen"[\s\S]*?(?=\s*<script)/);
if (!lock) throw new Error('No #lockscreen block found in the mobile index.html');
fs.writeFileSync(path.join(out, "index.html"), fs.readFileSync(path.join(out, "index.template.html"), "utf8").replace("<!--LOCKSCREEN-->", () => lock[0].trim()));
const style = mobileHtml.match(/<style>([\s\S]*?)<\/style>/);
if (!style) throw new Error("No <style> block found in the mobile index.html");
fs.writeFileSync(path.join(out, "mobile-base.css"), "/* GENERATED from the mobile index.html */\n" + style[1]);
for (const f of ["logo.jpg", "icon-192.png"]) fs.copyFileSync(path.join(src, f), path.join(out, f));
fs.copyFileSync(path.join(src, "icon-512.png"), path.join(root, "build", "icon.png"));
console.log("Synced from " + src + " (app version " + (js.match(/VERSION:"([^"]+)"/) || [])[1] + ")");
